CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL,
    login VARCHAR(255) NOT NULL,
    name VARCHAR(255),
    birthday DATE NOT NULL
);

CREATE TABLE IF NOT EXISTS mpa (
    mpa_id INT NOT NULL PRIMARY KEY,
    mpa_name VARCHAR(20) NOT NULL
);

CREATE TABLE IF NOT EXISTS genre (
    genre_id INT NOT NULL PRIMARY KEY,
    genre_name VARCHAR(50) NOT NULL
);

CREATE TABLE IF NOT EXISTS films (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    description VARCHAR(200),
    release_date DATE NOT NULL,
    duration INT NOT NULL CHECK (duration >= 1),
    mpa_id INT,

    CONSTRAINT fk_films_mpa
        FOREIGN KEY (mpa_id) REFERENCES mpa (mpa_id)
);

CREATE TABLE IF NOT EXISTS friendship (
    requester_id BIGINT NOT NULL,
    addressee_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,

    CONSTRAINT pk_friendship
        PRIMARY KEY (requester_id, addressee_id),

    CONSTRAINT fk_friendship_requester
        FOREIGN KEY (requester_id) REFERENCES users (id)
        ON DELETE CASCADE,

    CONSTRAINT fk_friendship_addressee
        FOREIGN KEY (addressee_id) REFERENCES users (id)
        ON DELETE CASCADE,

    CONSTRAINT chk_friendship_not_self
        CHECK (requester_id <> addressee_id)
);

CREATE TABLE IF NOT EXISTS film_likes (
    film_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,

    CONSTRAINT pk_film_likes
        PRIMARY KEY (film_id, user_id),

    CONSTRAINT fk_film_likes_film
        FOREIGN KEY (film_id) REFERENCES films (id)
        ON DELETE CASCADE,

    CONSTRAINT fk_film_likes_user
        FOREIGN KEY (user_id) REFERENCES users (id)
        ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS film_genre (
    film_id BIGINT NOT NULL,
    genre_id INT NOT NULL,

    CONSTRAINT pk_film_genre
        PRIMARY KEY (film_id, genre_id),

    CONSTRAINT fk_film_genre_film
        FOREIGN KEY (film_id) REFERENCES films (id)
        ON DELETE CASCADE,

    CONSTRAINT fk_film_genre_genre
        FOREIGN KEY (genre_id) REFERENCES genre (genre_id)
        ON DELETE CASCADE
);